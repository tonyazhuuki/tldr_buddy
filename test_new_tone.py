#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Тест нового TONE режима с обновленным промптом
"""

def test_new_tone():
    """Тест нового TONE режима"""
    
    print("🧠 ТЕСТ НОВОГО TONE РЕЖИМА (v1.3)")
    print("=" * 60)
    
    # Новый промпт TONE режима
    new_tone_prompt = """Кратко проанализируй психологию текста. Ничего не выдумывай; выводы — гипотезы, подкрепи цитатами. Язык ответа = язык входа.

🧠 ПСИХО-СНИМОК:
• 🎯 СКРЫТОЕ НАМЕРЕНИЕ: 1 фраза (операционально: «получить Х/избежать Y/проверить границы/получить внимание/уточнить условия»)
• 😶‍🌫️ ДОМИНИРУЮЩАЯ ЭМОЦИЯ: выбери из {спокойствие, тревога, злость/раздражение, грусть, вина/стыд, усталость, воодушевление, смешанные}
• 🗣️ СТИЛЬ ВЗАИМОДЕЙСТВИЯ: 1 фраза «как отвечать» (напр.: «коротко по пунктам», «эмпатично + один уточняющий вопрос», «жёстко зафиксировать границы и условия»)
• 🔎 ПРИЗНАКИ (цитаты): 2–4 коротких фрагмента текста-доказательства
• 🎛 УВЕРЕННОСТЬ: 0.0–1.0

Текст:
{text}"""
    
    print("📋 НОВЫЙ ПРОМПТ TONE РЕЖИМА:")
    print(new_tone_prompt)
    print("\n" + "=" * 60)
    
    # Тестовый текст
    test_text = """Я на маникюре, мне сложно одной рукой писать. Короче, я вообще думала не поехать, потому что так устала. И собачку уже можно... Я через Дубай, я собаку не смогу провести. Вот. Но в целом, если ты вдруг психанешь и решишь, то, может, я психану и решу. Оставлю кому-нибудь в маникюре собачку, я могу попасть. Так что пиши, и если ты психанешь, может, я психану."""
    
    print("📥 ТЕСТОВЫЙ ТЕКСТ:")
    print(test_text)
    print("\n" + "=" * 60)
    
    # Симуляция ответа GPT
    mock_response = """🧠 ПСИХО-СНИМОК:
• 🎯 СКРЫТОЕ НАМЕРЕНИЕ: получить решение от собеседника и избежать ответственности за выбор
• 😶‍🌫️ ДОМИНИРУЮЩАЯ ЭМОЦИЯ: усталость
• 🗣️ СТИЛЬ ВЗАИМОДЕЙСТВИЯ: эмпатично + один уточняющий вопрос о реальных намерениях
• 🔎 ПРИЗНАКИ (цитаты): "так устала", "думала не поехать", "если ты психанешь, может, я психану"
• 🎛 УВЕРЕННОСТЬ: 0.75"""
    
    print("🤖 ОТВЕТ GPT (новый формат):")
    print(mock_response)
    print("\n" + "=" * 60)
    
    # Симуляция парсинга и форматирования
    print("📤 ФОРМАТИРОВАННЫЙ ВЫВОД БОТА:")
    
    # Парсим результат (симуляция)
    lines = mock_response.split('\n')
    tone_data = {}
    
    for line in lines:
        line = line.strip()
        if not line:
            continue
            
        if line.startswith('🎯 СКРЫТОЕ НАМЕРЕНИЕ:'):
            tone_data['hidden_intent'] = line.replace('🎯 СКРЫТОЕ НАМЕРЕНИЕ:', '').strip()
        elif line.startswith('😶‍🌫️ ДОМИНИРУЮЩАЯ ЭМОЦИЯ:'):
            tone_data['dominant_emotion'] = line.replace('😶‍🌫️ ДОМИНИРУЮЩАЯ ЭМОЦИЯ:', '').strip()
        elif line.startswith('🗣️ СТИЛЬ ВЗАИМОДЕЙСТВИЯ:'):
            tone_data['interaction_style'] = line.replace('🗣️ СТИЛЬ ВЗАИМОДЕЙСТВИЯ:', '').strip()
    
    # Форматируем вывод как в боте
    formatted_output = f"""🧠 **Психологический анализ**:
  🎯 **Намерения**: {tone_data.get('hidden_intent', 'Не определено')}
  😶‍🌫️ **Эмоция**: {tone_data.get('dominant_emotion', 'Не определена')}
  🗣️ **Стиль**: {tone_data.get('interaction_style', 'Не определен')}"""
    
    print(formatted_output)
    print("\n" + "=" * 60)
    
    print("✅ КЛЮЧЕВЫЕ УЛУЧШЕНИЯ TONE РЕЖИМА v1.3:")
    print("• Подтверждение цитатами из текста")
    print("• Четкая шкала эмоций")
    print("• Оценка уверенности в анализе")
    print("• Операциональные формулировки намерений")
    print("• Доступен по команде /анализ или кнопке")

if __name__ == "__main__":
    test_new_tone() 